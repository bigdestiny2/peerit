#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  checkpointSignaturePayload,
  encodeReleaseControlVectorManifest,
  pinHistoryBundleHash,
  profilePinSignaturePayload
} from '../js/substrate/release-control-codec.mjs'
import { bytesEqual, bytesToHex, domainLengthHash } from '../js/substrate/release-control-primitives.mjs'
import { encodeReleaseControlRegistry } from '../js/substrate/release-control-registry.mjs'
import { buildReleaseControlFixture } from './release-control-fixture.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')

function outputs () {
  const fixture = buildReleaseControlFixture()
  const registryBytes = encodeReleaseControlRegistry()
  const vectors = [
    { path: 'release-control/fixture-release-public-key.bin', bytes: fixture.releasePublicKey },
    { path: 'release-control/fixture-wrong-public-key.bin', bytes: fixture.wrongPublicKey },
    { path: 'release-control/substrate-tuple-a.bin', bytes: fixture.tupleBytes[0] },
    { path: 'release-control/substrate-tuple-b.bin', bytes: fixture.tupleBytes[1] },
    { path: 'release-control/profile-pin-sequence-0.bin', bytes: fixture.pinBytes[0] },
    { path: 'release-control/profile-pin-sequence-1.bin', bytes: fixture.pinBytes[1] },
    { path: 'release-control/profile-pin-sequence-0-signature-payload.bin', bytes: profilePinSignaturePayload(fixture.pins[0]) },
    { path: 'release-control/checkpoint-sequence-0.bin', bytes: fixture.checkpointBytes[0] },
    { path: 'release-control/checkpoint-sequence-1.bin', bytes: fixture.checkpointBytes[1] },
    { path: 'release-control/checkpoint-sequence-0-signature-payload.bin', bytes: checkpointSignaturePayload(fixture.checkpoints[0]) },
    { path: 'release-control/pin-history-bundle.bin', bytes: fixture.bundleBytes }
  ]
  const generated = new Map()
  generated.set('protocol/peerit-release-control-v1.cenc', registryBytes)
  for (const vector of vectors) generated.set(path.posix.join('protocol/vectors', vector.path), vector.bytes)
  generated.set('protocol/vectors/peerit-release-control-v1.manifest.cenc', encodeReleaseControlVectorManifest(vectors))
  return { fixture, registryBytes, vectors, generated }
}

function compareCheckedIn (generated) {
  const problems = []
  for (const [relativePath, expected] of generated) {
    const absolutePath = path.join(root, relativePath)
    if (!fs.existsSync(absolutePath)) {
      problems.push(`${relativePath}: missing`)
      continue
    }
    const actual = new Uint8Array(fs.readFileSync(absolutePath))
    if (!bytesEqual(actual, expected)) problems.push(`${relativePath}: generated bytes drift`)
  }
  if (problems.length > 0) {
    for (const problem of problems) process.stderr.write(`${problem}\n`)
    process.exitCode = 1
  }
}

function writeGenerated (generated) {
  for (const [relativePath, bytes] of generated) {
    const absolutePath = path.join(root, relativePath)
    fs.mkdirSync(path.dirname(absolutePath), { recursive: true })
    fs.writeFileSync(absolutePath, bytes)
  }
}

const result = outputs()
if (check) compareCheckedIn(result.generated)
else writeGenerated(result.generated)

if (process.exitCode == null) {
  process.stdout.write(`${JSON.stringify({
    schema: 'PeeritReleaseControlSliceGenerationV1',
    fixtureOnly: true,
    productionProfileAbi: false,
    registryPath: 'protocol/peerit-release-control-v1.cenc',
    sliceArtifactHash: bytesToHex(domainLengthHash('peerit.release-control-slice-artifact-hash.v1', result.registryBytes)),
    vectorManifestPath: 'protocol/vectors/peerit-release-control-v1.manifest.cenc',
    vectorCount: result.vectors.length,
    fixtureBundleHash: bytesToHex(pinHistoryBundleHash(result.fixture.bundleBytes))
  }, null, 2)}\n`)
}
