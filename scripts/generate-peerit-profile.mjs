#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildPeeritProfileArtifacts } from '../js/substrate/profile-artifact-builder.mjs'
import { PEERIT_PROFILE_INVENTORY } from '../js/substrate/profile-inventory.mjs'
import { PROFILE_ARTIFACT_STATUS } from '../js/substrate/profile-status.mjs'
import { bytesEqual, bytesToHex } from '../js/substrate/release-control-primitives.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')
const sourcePath = 'docs/PEERIT-BLIND-SUBSTRATE-PROFILE.md'
const registryPath = 'protocol/peerit-profile-v1.cenc'
const manifestPath = 'protocol/vectors/peerit-profile-v1.manifest.cenc'
const managedVectorRoot = 'protocol/vectors/profile/declarations'

function expectedOutputs () {
  const sourceBytes = new Uint8Array(fs.readFileSync(path.join(root, sourcePath)))
  const result = buildPeeritProfileArtifacts(sourceBytes, PEERIT_PROFILE_INVENTORY)
  const generated = new Map([
    [registryPath, result.registryBytes],
    [manifestPath, result.vectorManifestBytes]
  ])
  for (const vector of result.vectors) generated.set(path.posix.join('protocol/vectors', vector.path), vector.bytes)
  return { result, generated }
}
function recursivelyListedFiles (relativeRoot) {
  const absoluteRoot = path.join(root, relativeRoot)
  if (!fs.existsSync(absoluteRoot)) return []
  const output = []
  const visit = (absoluteDirectory, relativeDirectory) => {
    for (const entry of fs.readdirSync(absoluteDirectory, { withFileTypes: true })) {
      const absolute = path.join(absoluteDirectory, entry.name)
      const relative = path.posix.join(relativeDirectory, entry.name)
      if (entry.isDirectory()) visit(absolute, relative)
      else if (entry.isFile()) output.push(relative)
      else output.push(relative)
    }
  }
  visit(absoluteRoot, relativeRoot)
  return output.sort()
}

function checkedInProblems (generated) {
  const problems = []
  for (const [relativePath, expected] of generated) {
    const absolutePath = path.join(root, relativePath)
    if (!fs.existsSync(absolutePath)) {
      problems.push(`${relativePath}: missing`)
      continue
    }
    const actual = new Uint8Array(fs.readFileSync(absolutePath))
    if (!bytesEqual(actual, expected)) problems.push(`${relativePath}: generated bytes drift`)
  }
  const expectedManaged = new Set([...generated.keys()].filter(relativePath => relativePath.startsWith(`${managedVectorRoot}/`)))
  for (const relativePath of recursivelyListedFiles(managedVectorRoot)) {
    if (!expectedManaged.has(relativePath)) problems.push(`${relativePath}: unexpected stale generated file`)
  }
  return problems
}

function statusProblems (result) {
  const expected = {
    sourcePath,
    registryArtifact: registryPath,
    vectorManifest: manifestPath,
    profileSha256: result.profileSha256,
    profileSpecHash: bytesToHex(result.profileSpecHash),
    profileAbiHash: bytesToHex(result.profileAbiHash),
    profileVectorSetHash: bytesToHex(result.profileVectorSetHash),
    inventoryCommitment: bytesToHex(result.inventoryCommitment),
    schemaCount: result.registry.schemas.length,
    vectorCount: result.vectors.length,
    fixtureOnly: false,
    deterministicRegistryReady: true,
    deterministicVectorsReady: true,
    codecLayoutIrComplete: true,
    boundedStructuralIrReady: true,
    semanticValidationComplete: false,
    recordCodecsReady: true,
    releaseReady: false
  }
  const problems = []
  for (const [field, value] of Object.entries(expected)) {
    if (PROFILE_ARTIFACT_STATUS[field] !== value) problems.push(`js/substrate/profile-status.mjs: ${field} drift`)
  }
  return problems
}

function writeGenerated (generated) {
  for (const [relativePath, bytes] of generated) {
    const absolutePath = path.join(root, relativePath)
    fs.mkdirSync(path.dirname(absolutePath), { recursive: true })
    fs.writeFileSync(absolutePath, bytes)
  }
}

const { result, generated } = expectedOutputs()
if (check) {
  const problems = [...checkedInProblems(generated), ...statusProblems(result)]
  if (problems.length > 0) {
    for (const problem of problems) process.stderr.write(`${problem}\n`)
    process.exitCode = 1
  }
} else {
  writeGenerated(generated)
  const problems = [...checkedInProblems(generated), ...statusProblems(result)]
  if (problems.length > 0) {
    for (const problem of problems) process.stderr.write(`${problem}\n`)
    process.exitCode = 1
  }
}

if (process.exitCode == null) {
  process.stdout.write(`${JSON.stringify({
    schema: 'PeeritProfileArtifactGenerationV1',
    fixtureOnly: false,
    registryComplete: true,
    codecLayoutIrComplete: true,
    codecsComplete: true,
    validatorComplete: false,
    releaseReady: false,
    sourcePath,
    profileSha256: result.profileSha256,
    registryPath,
    vectorManifestPath: manifestPath,
    declarationCount: result.registry.schemas.length,
    boundedCodecIrCount: result.codecIr.boundedSchemaCount,
    pendingClientExampleImportCount: result.codecIr.pendingClientExampleImportCount,
    vectorCount: result.vectors.length,
    profileSpecHash: bytesToHex(result.profileSpecHash),
    profileAbiHash: bytesToHex(result.profileAbiHash),
    profileVectorSetHash: bytesToHex(result.profileVectorSetHash),
    inventoryCommitment: bytesToHex(result.inventoryCommitment)
  }, null, 2)}\n`)
}
